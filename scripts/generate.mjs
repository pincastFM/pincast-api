#!/usr/bin/env node
// Writes src/generated/types.d.ts and src/generated/operations.js from the public API file,
// openapi/placecard-v1.openapi.json. No dependencies: it reads JSON and writes two text files.
//
//   node scripts/generate.mjs            write both files
//   node scripts/generate.mjs --check    write nothing; exit 1 when either file differs from the API file's
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { listOperations, resolve } from '../src/openapi.js'

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const API_FILE = join(ROOT, 'openapi', 'placecard-v1.openapi.json')
export const OUTPUTS = Object.freeze({
  types: 'src/generated/types.d.ts',
  operations: 'src/generated/operations.js',
})
const lit = (v) => (v === null ? 'null' : JSON.stringify(v))
const refName = (ref) => ref.split('/').pop()
const propKey = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name))
const requiredOnly = (list) => list.every((s) => Object.keys(s).every((k) => k === 'required'))

function comment(text, indent) {
  if (!text) return ''
  const first = String(text).split(/\n\s*\n/)[0].trim().replace(/\*\//g, '*\\/')
  const lines = first.split('\n').map((l) => `${indent} * ${l}`.trimEnd())
  return `${indent}/**\n${lines.join('\n')}\n${indent} */\n`
}

// A TypeScript type for a JSON Schema (the subset the API file uses).
function ts(schema, indent = '') {
  if (!schema || schema === true) return 'unknown'
  if (schema.$ref) return refName(schema.$ref)
  if ('const' in schema) return lit(schema.const)
  if (schema.enum) return schema.enum.map(lit).join(' | ')
  if (schema.oneOf && !requiredOnly(schema.oneOf)) return schema.oneOf.map((s) => ts(s, indent)).join(' | ')
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : schema.properties ? ['object'] : []
  if (!types.length) return 'unknown'
  return types.map((t) => {
    if (t === 'string') return 'string'
    if (t === 'integer' || t === 'number') return 'number'
    if (t === 'boolean') return 'boolean'
    if (t === 'null') return 'null'
    if (t === 'array') return `Array<${ts(schema.items, indent)}>`
    if (t === 'object') return object(schema, indent)
    return 'unknown'
  }).join(' | ')
}

// An object type. A oneOf of `required` lists (PersonRequest) becomes one object per branch,
// where the other branches' fields are `?: never`, so exactly one of them can be sent.
function object(schema, indent) {
  const props = schema.properties || {}
  const required = new Set(schema.required || [])
  const branches = schema.oneOf && requiredOnly(schema.oneOf) ? schema.oneOf.map((b) => b.required || []) : [null]
  const inBranches = branches.flatMap((b) => b || [])
  const inner = `${indent}  `
  const bodies = branches.map((branch) => {
    const lines = []
    for (const [name, sub] of Object.entries(props)) {
      let optional = !required.has(name)
      let type = ts(sub, inner)
      if (branch && branch.includes(name)) optional = false
      else if (branch && inBranches.includes(name)) { optional = true; type = 'never' }
      lines.push(`${comment(sub.description, inner)}${inner}${propKey(name)}${optional ? '?' : ''}: ${type}`)
    }
    const extra = schema.additionalProperties
    if (extra && extra !== false) lines.push(`${inner}[key: string]: ${extra === true ? 'unknown' : ts(extra, inner)}`)
    else if (extra === undefined && !lines.length) lines.push(`${inner}[key: string]: unknown`)
    return lines.length ? `{\n${lines.join('\n')}\n${indent}}` : '{}'
  })
  return bodies.length === 1 ? bodies[0] : bodies.map((b) => `(${b})`).join(' | ')
}

function jsonBody(doc, node) {
  return resolve(doc, node)?.content?.['application/json']?.schema ?? null
}

export function generate(doc, sha256) {
  const ops = listOperations(doc)
  const head = `Generated by scripts/generate.mjs from openapi/placecard-v1.openapi.json\n// (${doc.info.title} ${doc.info.version}, sha256 ${sha256}). Do not edit: run npm run generate.`

  // types.d.ts
  const t = [`// ${head}`, '']
  for (const [name, schema] of Object.entries(doc.components?.schemas || {})) {
    t.push(`${comment(schema.description, '')}export type ${name} = ${ts(schema)}`, '')
  }
  if (doc.components?.schemas?.ErrorData) t.push('/** Every code an error can carry. */', "export type ErrorCode = ErrorData['code']", '')
  t.push('/** Each operation in the API file: its address, what it takes and what it answers. */', 'export interface Operations {')
  for (const o of ops) {
    const pathParams = o.params.filter((p) => p.in === 'path')
    const query = o.params.filter((p) => p.in === 'query')
    const body = o.body ? ts(jsonBody(doc, o.body), '    ') : 'never'
    const ok = jsonBody(doc, o.op.responses?.['200'])
    t.push(
      `${comment(`${o.method} ${o.path}: ${o.op.summary || ''}`.trim(), '  ')}  ${o.id}: {`,
      `    method: ${lit(o.method)}`,
      `    path: ${lit(o.path)}`,
      `    pathParams: {${pathParams.map((p) => ` ${propKey(p.name)}: ${ts(p.schema, '    ')}`).join(';')}${pathParams.length ? ' ' : ''}}`,
      `    query: {${query.map((p) => ` ${propKey(p.name)}${p.required ? '' : '?'}: ${ts(p.schema, '    ')}`).join(';')}${query.length ? ' ' : ''}}`,
      `    body: ${body}${o.body && !o.body.required ? ' | undefined' : ''}`,
      `    response: ${ok ? ts(ok, '    ') : 'unknown'}`,
      `    key: ${o.security.length > 0}`,
      `    idempotencyKey: ${o.params.some((p) => p.in === 'header' && p.name === 'Idempotency-Key')}`,
      '  }',
    )
  }
  t.push('}', '', '/** The id of each operation, which is also the client method that makes it. */', 'export type OperationId = keyof Operations', '')

  // operations.js
  const j = [`// ${head}`, '']
  j.push(`export const apiFile = Object.freeze(${JSON.stringify({ title: doc.info.title, version: doc.info.version, sha256 })})`, '')
  j.push(`export const servers = Object.freeze(${JSON.stringify((doc.servers || []).map((s) => s.url))})`, '')
  j.push('export const operations = Object.freeze({')
  for (const o of ops) {
    const entry = {
      method: o.method,
      path: o.path,
      pathParams: o.params.filter((p) => p.in === 'path').map((p) => p.name),
      query: o.params.filter((p) => p.in === 'query').map((p) => p.name),
      body: o.body ? (o.body.required ? 'required' : 'optional') : 'none',
      key: o.security.length > 0,
      idempotencyKey: o.params.some((p) => p.in === 'header' && p.name === 'Idempotency-Key'),
    }
    j.push(`  ${o.id}: Object.freeze(${JSON.stringify(entry)}),`)
  }
  j.push('})', '')
  const codes = doc.components?.schemas?.ErrorData?.properties?.code?.enum || []
  j.push(`export const errorCodes = Object.freeze(${JSON.stringify(codes)})`, '')

  return { [OUTPUTS.types]: t.join('\n'), [OUTPUTS.operations]: j.join('\n') }
}

export function generateFromFile(file = API_FILE) {
  const bytes = readFileSync(file)
  return generate(JSON.parse(bytes.toString('utf8')), createHash('sha256').update(bytes).digest('hex'))
}

// The generated files that differ from what `file` gives (an empty list when both are fresh).
export function staleOutputs(file = API_FILE) {
  const want = generateFromFile(file)
  return Object.keys(want).filter((rel) => {
    try { return readFileSync(join(ROOT, rel), 'utf8') !== want[rel] } catch { return true }
  })
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  if (process.argv.includes('--check')) {
    const stale = staleOutputs()
    if (stale.length) {
      console.error(`stale: ${stale.join(', ')}. Run npm run generate.`)
      process.exit(1)
    }
    console.log('generated files match the API file')
  } else {
    for (const [rel, text] of Object.entries(generateFromFile())) {
      writeFileSync(join(ROOT, rel), text)
      console.log(`wrote ${rel}`)
    }
  }
}
